class EmailReporter:
    """Manages report delivery via logged-in Chrome Gmail or SMTP."""

    @staticmethod
    def send_via_smtp(
        report: SessionReport,
        recipient_email: str,
        host: str = "smtp.gmail.com",
        port: int = 587,
        username: str = "",
        password: str = "",
        sender_email: Optional[str] = None,
        log_queue: Optional[queue.Queue] = None,
    ) -> bool:
        """Deliver report email using SMTP with TLS or SSL."""
        if not recipient_email or "@" not in recipient_email:
            if log_queue:
                emit(log_queue, f"Email report skipped: invalid recipient '{recipient_email}'.", logging.WARNING)
            return False

        sender = (sender_email or username or report.account_email or "").strip()
        if not sender or "@" not in sender:
            if log_queue:
                emit(log_queue, "SMTP report skipped: sender email address is not configured.", logging.WARNING)
            return False

        if not password:
            if log_queue:
                emit(log_queue, "SMTP report skipped: password / app password is not configured.", logging.WARNING)
            return False

        subject = report.generate_subject()
        plain_text = report.generate_plain_text()
        html_content = report.generate_html()

        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = sender
        msg["To"] = recipient_email
        msg.attach(MIMEText(plain_text, "plain", "utf-8"))
        msg.attach(MIMEText(html_content, "html", "utf-8"))

        try:
            if log_queue:
                emit(log_queue, f"Connecting to SMTP server {host}:{port} to send session report...")

            if port == 465:
                server = smtplib.SMTP_SSL(host, port, timeout=25)
            else:
                server = smtplib.SMTP(host, port, timeout=25)
                server.ehlo()
                server.starttls()
                server.ehlo()

            user_login = (username or sender).strip()
            server.login(user_login, password)
            server.sendmail(sender, [recipient_email], msg.as_string())
            server.quit()

            if log_queue:
                emit(log_queue, f"Session watch time report successfully emailed to '{recipient_email}' via SMTP.")
            return True

        except Exception as exc:
            if log_queue:
                emit(log_queue, f"SMTP email delivery failed: {exc}", logging.ERROR)
            return False

    @staticmethod
    def send_via_browser_gmail(
        driver: Any,
        report: SessionReport,
        recipient_email: str,
        log_queue: Optional[queue.Queue] = None,
    ) -> bool:
        """Deliver report email using the logged-in Gmail session in the active Chrome browser."""
        if not driver:
            if log_queue:
                emit(log_queue, "Browser Gmail delivery failed: browser driver is unavailable.", logging.WARNING)
            return False

        if not recipient_email or "@" not in recipient_email:
            if log_queue:
                emit(log_queue, f"Browser Gmail delivery skipped: invalid recipient '{recipient_email}'.", logging.WARNING)
            return False

        subject = report.generate_subject()
        plain_text = report.generate_plain_text()

        try:
            if log_queue:
                emit(log_queue, f"Opening logged-in Gmail web session to send report to '{recipient_email}'...")

            # Direct Gmail compose URL with prefilled recipient and subject
            compose_url = (
                f"https://mail.google.com/mail/?view=cm&fs=1"
                f"&to={quote(recipient_email)}"
                f"&su={quote(subject)}"
            )
            driver.get(compose_url)
            time.sleep(3.5)

            # Wait for compose window to load
            wait = WebDriverWait(driver, 15)

            # Check if Gmail redirected to sign-in (not logged in)
            current_url = driver.current_url or ""
            if "accounts.google.com" in current_url:
                if log_queue:
                    emit(log_queue, "Browser Gmail delivery failed: Google account is not signed in.", logging.ERROR)
                return False

            # 1. Ensure Recipient is populated
            to_field = None
            try:
                to_field = driver.find_element(By.XPATH, "//input[@name='to' or @aria-label='To' or @aria-label='To recipients']")
            except Exception:
                pass

            if to_field:
                try:
                    val = to_field.get_attribute("value") or ""
                    if recipient_email.lower() not in val.lower():
                        to_field.click()
                        to_field.clear()
                        to_field.send_keys(recipient_email)
                        to_field.send_keys(Keys.ENTER)
                except Exception:
                    pass

            # 2. Locate the compose message body (with wait retry for Gmail to render)
            body_element = None
            body_selectors = [
                "//div[@role='textbox' and (contains(@aria-label, 'Message Body') or contains(@aria-label, 'Body'))]",
                "//div[contains(@class, 'editable') and @role='textbox']",
                "//div[@aria-label='Message Body']",
                "//div[@role='textbox']",
            ]
            start_wait = time.time()
            while time.time() - start_wait < 18:
                for sel in body_selectors:
                    try:
                        elems = driver.find_elements(By.XPATH, sel)
                        for el in elems:
                            if el.is_displayed():
                                body_element = el
                                break
                        if body_element:
                            break
                    except Exception:
                        continue
                if body_element:
                    break
                time.sleep(1.0)

            if not body_element:
                if log_queue:
                    emit(log_queue, "Browser Gmail delivery failed: could not locate Gmail compose text area.", logging.ERROR)
                return False

            # Focus and write the body content
            body_element.click()
            time.sleep(0.5)

            # Write text cleanly into the contenteditable div
            try:
                # Use execute_script for clean multiline formatting without key simulation delays
                driver.execute_script(
                    "arguments[0].innerText = arguments[1]; arguments[0].dispatchEvent(new Event('input', {bubbles: true}));",
                    body_element,
                    plain_text,
                )
            except Exception:
                # Fallback to character chunk typing
                lines = plain_text.split("\n")
                for line in lines:
                    body_element.send_keys(line)
                    body_element.send_keys(Keys.SHIFT, Keys.ENTER)

            time.sleep(1.0)

            # 3. Trigger Send
            sent = False

            # Option A: Send button click
            send_btn_selectors = [
                "//div[@role='button' and @data-tooltip and contains(@data-tooltip, 'Send')]",
                "//div[@role='button' and @aria-label and contains(@aria-label, 'Send')]",
                "//div[@role='button' and text()='Send']",
                "//div[contains(@class, 'T-I') and contains(@class, 'aoO')]",
            ]
            for sel in send_btn_selectors:
                try:
                    buttons = driver.find_elements(By.XPATH, sel)
                    for btn in buttons:
                        if btn.is_displayed():
                            btn.click()
                            sent = True
                            break
                    if sent:
                        break
                except Exception:
                    continue

            # Option B: Shortcut fallback (Ctrl+Enter)
            if not sent:
                try:
                    body_element.send_keys(Keys.CONTROL, Keys.ENTER)
                    sent = True
                except Exception:
                    pass

            if not sent:
                if log_queue:
                    emit(log_queue, "Browser Gmail delivery failed: could not trigger Send button.", logging.ERROR)
                return False

            # Wait briefly to confirm send
            time.sleep(2.5)
            if log_queue:
                emit(log_queue, f"Session watch time report successfully sent to '{recipient_email}' via logged-in Gmail browser.")
            return True

        except Exception as exc:
            if log_queue:
                emit(log_queue, f"Browser Gmail delivery error: {exc}", logging.ERROR)
            return False

    @classmethod
    def dispatch_report(
        cls,
        report: SessionReport,
        config_mgr: Any,
        driver: Optional[Any] = None,
        account: Optional[Account] = None,
        log_queue: Optional[queue.Queue] = None,
    ) -> bool:
        """Route report delivery based on configuration and available transports."""
        if not config_mgr:
            return False

        is_enabled = config_mgr.get_bool("EmailReportingEnabled", False)
        recipient = (config_mgr.get_setting("ReportRecipientEmail", "") or "").strip()

        if not is_enabled:
            return False

        if not recipient:
            if log_queue:
                emit(
                    log_queue,
                    "Session watch time email reporting is enabled, but no Recipient Email is set in Settings.",
                    logging.WARNING,
                )
            return False

        method = config_mgr.get_setting("ReportEmailMethod", "Auto").strip()
        smtp_host = config_mgr.get_setting("SmtpHost", "smtp.gmail.com")
        smtp_port = config_mgr.get_int("SmtpPort", 587)
        smtp_user = config_mgr.get_setting("SmtpUsername", "") or (account.email if account else "")
        smtp_pass = config_mgr.get_setting("SmtpPassword", "") or (account.password if account else "")
        sender = config_mgr.get_setting("SenderEmail", "") or smtp_user

        has_smtp_creds = bool(smtp_pass and (smtp_user or sender))

        # 1. Explicit SMTP Connection method
        if "smtp" in method.lower() and "auto" not in method.lower() and "browser" not in method.lower():
            return cls.send_via_smtp(
                report=report,
                recipient_email=recipient,
                host=smtp_host,
                port=smtp_port,
                username=smtp_user,
                password=smtp_pass,
                sender_email=sender,
                log_queue=log_queue,
            )

        # 2. Explicit Browser Gmail method
        if "browser" in method.lower() and "auto" not in method.lower():
            if driver is not None:
                return cls.send_via_browser_gmail(driver, report, recipient, log_queue=log_queue)
            elif has_smtp_creds:
                if log_queue:
                    emit(log_queue, "Browser driver unavailable; falling back to SMTP.", logging.WARNING)
                return cls.send_via_smtp(
                    report=report,
                    recipient_email=recipient,
                    host=smtp_host,
                    port=smtp_port,
                    username=smtp_user,
                    password=smtp_pass,
                    sender_email=sender,
                    log_queue=log_queue,
                )
            else:
                if log_queue:
                    emit(log_queue, "Browser driver unavailable and SMTP credentials not configured.", logging.ERROR)
                return False

        # 3. Auto Mode:
        # Prefer browser Gmail if driver is open and ready; fallback to SMTP if needed.
        # Or if SMTP credentials are provided and driver is not present, use SMTP.
        if driver is not None:
            browser_ok = cls.send_via_browser_gmail(driver, report, recipient, log_queue=log_queue)
            if browser_ok:
                return True
            if has_smtp_creds:
                if log_queue:
                    emit(log_queue, "Browser Gmail send did not succeed; retrying via SMTP fallback...", logging.INFO)
                return cls.send_via_smtp(
                    report=report,
                    recipient_email=recipient,
                    host=smtp_host,
                    port=smtp_port,
                    username=smtp_user,
                    password=smtp_pass,
                    sender_email=sender,
                    log_queue=log_queue,
                )
            return False

        if has_smtp_creds:
            return cls.send_via_smtp(
                report=report,
                recipient_email=recipient,
                host=smtp_host,
                port=smtp_port,
                username=smtp_user,
                password=smtp_pass,
                sender_email=sender,
                log_queue=log_queue,
            )

        if log_queue:
            emit(
                log_queue,
                "Email reporting could not dispatch: no active browser session and no SMTP credentials configured.",
                logging.WARNING,
            )
        return False
